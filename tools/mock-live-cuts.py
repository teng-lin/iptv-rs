#!/usr/bin/env python3
"""Mock live IPTV provider that cuts connections (synthetic data only).

Reproduces two provider behaviours every live player has to survive:

* Live HLS: /live/<name>.m3u8 answers 302 to a tokenized address
  /t/<token>/<name>.m3u8; reloading the playlist there answers 403 once the
  token is older than --hls-token-secs (default 40), as a provider whose
  redirect tokens expire. Segments keep working. A player that reloads the
  redirected playlist (ffmpeg, mpv) hits EOF; one that goes back to the
  original address gets a new token.
* Live MPEG-TS: /live/<name>.ts streams the live segments in real time
  (no Content-Length) and closes the connection after --ts-close-secs
  (default 70).

The live picture is generated by ffmpeg (test pattern, a burned-in wall
clock and frame counter, a sine tone): HLS with 2 s segments into a
temporary directory, kept --window segments long. An ffmpeg without the
drawtext filter (Homebrew's has no freetype) leaves the wall clock out:
testsrc2's own time code and frame counter stay. Every <name> plays the
same live stream. /playlist.m3u lists an HLS and a TS channel (and a
second of each, to zap between) at the address the request came to.

Usage:
  tools/mock-live-cuts.py [--port 8090] [--hls-token-secs 40]
                          [--ts-close-secs 70] [--burst-segs 1]
                          [--open-delay-ms 0]
  # desktop app: add the playlist http://127.0.0.1:8090/playlist.m3u
  # mpv:         mpv http://127.0.0.1:8090/live/a.m3u8
Each request is logged (path only; tokens are synthetic).
"""

import argparse
import http.server
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import threading
import time

ARGS = None
LIVE_DIR = None
STARTED = time.time()
SEG_RE = re.compile(r"seg(\d+)\.ts$")


def log(msg):
    sys.stdout.write("%.3f %s\n" % (time.time() - STARTED, msg))
    sys.stdout.flush()


def has_drawtext():
    out = subprocess.run(["ffmpeg", "-hide_banner", "-filters"],
                         capture_output=True, text=True).stdout
    return re.search(r"\bdrawtext\b", out) is not None


def find_font(asked):
    """A monospace font file: the one asked for, a usual one, fc-match's."""
    candidates = [asked, "/usr/share/fonts/TTF/DejaVuSansMono.ttf",
                  "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
                  "/System/Library/Fonts/Menlo.ttc"]
    for c in candidates:
        if c and os.path.isfile(c):
            return c
    try:
        return subprocess.run(["fc-match", "-f", "%{file}", "monospace"],
                              capture_output=True, text=True).stdout.strip() or None
    except OSError:
        return None


def start_encoder(out):
    """ffmpeg making the live HLS stream into `out` (real time)."""
    font = find_font(ARGS.font)
    vf = []
    if font and has_drawtext():
        vf = ["-vf", (
            "drawtext=fontfile='%s':fontsize=48:fontcolor=white:box=1:boxcolor=black@0.6:"
            "x=20:y=20:text='%%{localtime\\:%%H\\\\\\:%%M\\\\\\:%%S} f%%{frame_num}'" % font
        )]
    else:
        log("no drawtext (or no font): the picture has testsrc2's time code only")
    cmd = [
        "ffmpeg", "-loglevel", "error", "-nostdin",
        "-re", "-f", "lavfi", "-i", "testsrc2=size=640x360:rate=25",
        "-re", "-f", "lavfi", "-i", "sine=frequency=660:sample_rate=48000",
        *vf,
        "-c:v", "libx264", "-preset", "ultrafast", "-tune", "zerolatency",
        "-g", "50", "-keyint_min", "50", "-sc_threshold", "0", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", "96k",
        "-f", "hls", "-hls_time", "2", "-hls_list_size", str(ARGS.window),
        "-hls_flags", "delete_segments+omit_endlist",
        "-hls_delete_threshold", "8",
        "-hls_segment_filename", os.path.join(out, "seg%d.ts"),
        os.path.join(out, "live.m3u8"),
    ]
    return subprocess.Popen(cmd)


def read_live_playlist():
    try:
        with open(os.path.join(LIVE_DIR, "live.m3u8"), "rb") as f:
            return f.read()
    except OSError:
        return None


def segment_numbers():
    """Complete segments listed in the live playlist, oldest first."""
    body = read_live_playlist() or b""
    return [int(m.group(1)) for m in re.finditer(rb"seg(\d+)\.ts", body)]


class Handler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):
        pass

    def reply(self, status, body=b"", ctype="text/plain", headers=()):
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        for k, v in headers:
            self.send_header(k, v)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def do_HEAD(self):
        self.do_GET()

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        parts = [p for p in path.split("/") if p]
        if path == "/playlist.m3u":
            return self.playlist()
        if len(parts) == 2 and parts[0] == "live" and ARGS.open_delay_ms > 0:
            # A distant provider: every new connection takes this long.
            time.sleep(ARGS.open_delay_ms / 1000.0)
        if len(parts) == 2 and parts[0] == "live" and parts[1].endswith(".m3u8"):
            token = "%x-%x" % (int(time.time() * 1000), os.getpid())
            log("302 %s -> token %s" % (path, token))
            return self.reply(302, headers=[("Location", "/t/%s/%s" % (token, parts[1]))])
        if len(parts) == 2 and parts[0] == "live" and parts[1].endswith(".ts"):
            return self.stream_ts(path)
        if len(parts) == 3 and parts[0] == "t":
            return self.tokenized(parts[1], parts[2])
        self.reply(404, b"not found")

    def playlist(self):
        host = self.headers.get("Host", "127.0.0.1:%d" % ARGS.port)
        lines = ["#EXTM3U"]
        for name, title in [
            ("a.m3u8", "Cut HLS A"), ("b.m3u8", "Cut HLS B"),
            ("a.ts", "Cut TS A"), ("b.ts", "Cut TS B"),
        ]:
            lines.append('#EXTINF:-1 tvg-id="cut-%s" group-title="Cuts",%s' % (name, title))
            lines.append("http://%s/live/%s" % (host, name))
        self.reply(200, ("\n".join(lines) + "\n").encode(), "audio/x-mpegurl")

    def tokenized(self, token, name):
        try:
            issued = int(token.split("-")[0], 16) / 1000.0
        except ValueError:
            return self.reply(403, b"bad token")
        if name.endswith(".m3u8"):
            age = time.time() - issued
            if age > ARGS.hls_token_secs:
                log("403 playlist reload, token %s age %.1f s" % (token, age))
                return self.reply(403, b"token expired")
            body = read_live_playlist()
            if body is None:
                return self.reply(503, b"starting")
            return self.reply(200, body, "application/vnd.apple.mpegurl",
                              [("Cache-Control", "no-cache")])
        m = SEG_RE.search(name)
        if not m:
            return self.reply(404, b"not found")
        try:
            with open(os.path.join(LIVE_DIR, name), "rb") as f:
                body = f.read()
        except OSError:
            return self.reply(404, b"gone")
        self.reply(200, body, "video/mp2t")

    def stream_ts(self, path):
        """The live segments as one endless TS body, closed after a while."""
        segs = segment_numbers()
        if not segs:
            return self.reply(503, b"starting")
        log("TS open %s (closes in %.0f s)" % (path, ARGS.ts_close_secs))
        self.send_response(200)
        self.send_header("Content-Type", "video/mp2t")
        self.send_header("Connection", "close")
        self.end_headers()
        if self.command == "HEAD":
            return
        self.close_connection = True
        opened = time.time()
        # Like a provider's burst: the newest --burst-segs complete segments.
        nxt = segs[-ARGS.burst_segs] if len(segs) >= ARGS.burst_segs else segs[0]
        try:
            while time.time() - opened < ARGS.ts_close_secs:
                listed = segment_numbers()
                if listed and nxt < listed[0]:
                    nxt = listed[0]
                if nxt not in listed:
                    time.sleep(0.1)
                    continue
                with open(os.path.join(LIVE_DIR, "seg%d.ts" % nxt), "rb") as f:
                    data = f.read()
                nxt += 1
                # Paced over the segment's 2 s, as a live server sends it.
                chunks = [data[i:i + 18800] for i in range(0, len(data), 18800)]
                for chunk in chunks:
                    if time.time() - opened >= ARGS.ts_close_secs:
                        break
                    self.wfile.write(chunk)
                    self.wfile.flush()
                    time.sleep(1.8 / max(len(chunks), 1))
        except (BrokenPipeError, ConnectionResetError):
            log("TS client left %s after %.1f s" % (path, time.time() - opened))
            return
        log("TS close %s after %.1f s" % (path, time.time() - opened))


class Server(http.server.ThreadingHTTPServer):
    daemon_threads = True

    def handle_error(self, request, client_address):
        if not isinstance(sys.exc_info()[1], (ConnectionError, BrokenPipeError)):
            super().handle_error(request, client_address)


def main():
    global ARGS, LIVE_DIR
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--port", type=int, default=8090)
    p.add_argument("--hls-token-secs", type=float, default=40.0)
    p.add_argument("--ts-close-secs", type=float, default=70.0)
    p.add_argument("--burst-segs", type=int, default=1,
                   help="complete segments a TS connection starts with")
    p.add_argument("--window", type=int, default=6, help="segments in the live playlist")
    p.add_argument("--open-delay-ms", type=int, default=0,
                   help="delay before answering /live/ (a slow provider)")
    p.add_argument("--font", default=None, help="font file for the wall clock")
    ARGS = p.parse_args()
    LIVE_DIR = tempfile.mkdtemp(prefix="mock-live-cuts-")
    encoder = start_encoder(LIVE_DIR)

    def stop(*_):
        encoder.terminate()
        shutil.rmtree(LIVE_DIR, ignore_errors=True)
        os._exit(0)

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    threading.Thread(target=lambda: (encoder.wait(), log("encoder exited"), stop()),
                     daemon=True).start()
    server = Server(("0.0.0.0", ARGS.port), Handler)
    log("mock live cuts on :%d (HLS token %.0f s, TS close %.0f s)"
        % (ARGS.port, ARGS.hls_token_secs, ARGS.ts_close_secs))
    server.serve_forever()


if __name__ == "__main__":
    main()
